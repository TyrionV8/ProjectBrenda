def build(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    images = {}
    for name, rows in ICONS.items():
        c = Canvas(10, 10)
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == "#":
                    c.set(x, y, (255, 255, 255, 255))
                elif ch == "+":
                    c.set(x, y, (255, 255, 255, 70))
        c.image().save(os.path.join(out_dir, f"{name}.png"))
        images[name] = c.image()
    return images
